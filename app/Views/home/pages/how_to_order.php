<h5 class="fw-bold mb-3">Langkah-Langkah Order</h5>

<h6 class="fw-semibold mt-4">1. Siapkan Akun</h6>
<p class="text-muted">Daftar di web ini bila belum punya, atau masuk dengan email yang kamu pakai saat daftar.</p>

<h6 class="fw-semibold mt-4">2. Pilih Layanan dari Dashboard</h6>
<ul class="text-muted">
    <li><strong>Order → Top Up</strong>: isi nominal USD dan akun PayPal tujuan.</li>
    <li><strong>Order → Jasa Bayar</strong>: tempel link item yang dibeli beserta harganya dalam USD.</li>
</ul>

<h6 class="fw-semibold mt-4">3. Periksa Rekap, Lalu Bayar</h6>
<p class="text-muted">
    Detail order menampilkan komponen biaya lengkap. Transfer ke rekening yang tercantum sampai nominal
    dihitung termasuk, lalu nyalakan tombol konfirmasi bila tersedia.
</p>

<h6 class="fw-semibold mt-4">4. Pantau Status Order</h6>
<p class="text-muted">
    Status berubah menjadi <code>processing</code> saat tim kami mulai bekerja dan <code>done</code> setelah
    saldo/item selesai. Bila butuh bantuan, hubungi kami dengan menyebut nomor order.
</p>

